"""Generate lossless SVG paths from the app logo, including its original alpha.

Run from the repository root:
    uv run --project apps/backend python scripts/generate-rockit-logo.py

Pixel-aligned paths deliberately preserve the supplied artwork rather than
approximating its outline or gradient with a new drawing.
"""

from collections import defaultdict
from pathlib import Path

from PIL import Image


def main() -> None:
    root = Path(__file__).resolve().parent.parent
    public = root / "apps/web/public"
    with Image.open(public / "logo-512.png") as source:
        image = source.convert("RGBA")

    # Merge equal horizontal runs vertically, then group them by RGBA color.
    paths: dict[tuple[int, int, int, int], list[str]] = defaultdict(list)
    active: dict[tuple[int, int, tuple[int, int, int, int]], int] = {}

    def finish(key: tuple[int, int, tuple[int, int, int, int]], bottom: int) -> None:
        start, end, color = key
        top = active[key]
        paths[color].append(f"M{start} {top}h{end - start}v{bottom - top}H{start}z")

    for y in range(image.height):
        row = list(image.crop((0, y, image.width, y + 1)).getdata())
        runs = {}
        start = 0
        for x in range(1, image.width + 1):
            if x == image.width or row[x] != row[start]:
                if row[start][3]:
                    key = (start, x, row[start])
                    runs[key] = active.get(key, y)
                start = x
        for key in active:
            if key not in runs:
                finish(key, y)
        active = runs
    for key in active:
        finish(key, image.height)

    lines = [
        '<svg xmlns="http://www.w3.org/2000/svg" '
        f'viewBox="0 0 {image.width} {image.height}" shape-rendering="geometricPrecision">',
        "  <!-- Generated by scripts/generate-rockit-logo.py from logo-512.png. -->",
    ]
    for (red, green, blue, alpha), commands in sorted(paths.items()):
        opacity = "" if alpha == 255 else f' fill-opacity="{alpha / 255:.8f}"'
        lines.append(
            f'  <path fill="#{red:02x}{green:02x}{blue:02x}"{opacity} d="{"".join(commands)}"/>'
        )
    lines.append("</svg>")
    (public / "rockit-logo.svg").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
