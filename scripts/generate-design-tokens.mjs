import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const tokens = JSON.parse(readFileSync(new URL("packages/theme/src/tokens.json", root), "utf8"));
const semantic = readFileSync(new URL("packages/theme/src/semantic.css", root), "utf8");
const declarations = (theme, indent = "    ") =>
    Object.entries(theme).map(([key, value]) => `${indent}--theme-${key}: ${value};`).join("\n");
const scales = [
    ...Object.entries(tokens.radius).map(([key, value]) => `    --radius-${key}: ${value}px;`),
    ...Object.entries(tokens.spacing).map(([key, value]) => `    --space-${key}: ${value}px;`),
    ...Object.entries(tokens.typography).map(([key, value]) => `    --font-size-${key}: ${value}px;`),
    ...Object.entries(tokens.motion).map(([key, value]) => `    --motion-${key}: ${value}ms;`),
].join("\n");
const css = `/* Generated by scripts/generate-design-tokens.mjs. Edit packages/theme/src/tokens.json. */
:root {
    color-scheme: dark;
${declarations(tokens.themes.dark)}
${scales}
}

${semantic}
@property --cf-accent {
    syntax: "<color>";
    inherits: true;
    initial-value: ${tokens.themes.dark["media-accent"]};
}

:root[data-theme="light"] {
    color-scheme: light;
${declarations(tokens.themes.light)}
}

@media (prefers-color-scheme: light) {
    :root[data-theme="system"] {
        color-scheme: light;
${declarations(tokens.themes.light, "        ")}
    }
}
`;
const output = new URL("apps/web/styles/tokens/theme.css", root);
if (process.argv.includes("--check")) {
    if (readFileSync(output, "utf8") !== css) throw new Error("Generated design tokens are stale; run pnpm generate:theme");
} else {
    writeFileSync(output, css);
}
